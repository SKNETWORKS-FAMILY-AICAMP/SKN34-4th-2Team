import { describe, expect, it } from 'vitest';

import { defaultQuestions, splitQuestions } from '../companyQuestions';

const ids = () => {
  let n = 0;
  return () => `q${++n}`;
};

const shape = (text: string) => splitQuestions(text, ids()).map(({ question, limit }) => ({ question, limit }));

describe('붙여 넣은 자소서 문항 나누기', () => {
  it('번호 문항과 괄호 속 글자 수를 나누고, 머리글은 버린다', () => {
    expect(
      shape(`[자기소개서]
1. 클라우드랩에 지원한 이유와 입사 후 포부를 기술하시오. (공백 포함 600자 이내)
2. 본인이 주도적으로 문제를 해결한 경험을 서술하시오. (공백 포함 1,000자 이내)`),
    ).toEqual([
      { question: '클라우드랩에 지원한 이유와 입사 후 포부를 기술하시오.', limit: 600 },
      { question: '본인이 주도적으로 문제를 해결한 경험을 서술하시오.', limit: 1000 },
    ]);
  });

  it('작성 안내 줄은 문항에 붙이지 않고, 다음 줄의 글자 수는 읽는다', () => {
    expect(
      shape(`① 자신을 소개하고, 지원한 직무를 선택한 이유를 작성해 주세요.
(* Guide : 본인의 가치관과 경험을 구체적으로 작성해 주세요.)
(500자 이내)
② 협업 경험을 작성해 주세요.`),
    ).toEqual([
      { question: '자신을 소개하고, 지원한 직무를 선택한 이유를 작성해 주세요.', limit: 500 },
      { question: '협업 경험을 작성해 주세요.', limit: null },
    ]);
  });

  it('두 줄로 접힌 번호 문항은 잇는다', () => {
    expect(shape('Q1. 팀 프로젝트에서 맡은 역할과\n기여를 작성하시오. 800자')).toEqual([
      { question: '팀 프로젝트에서 맡은 역할과 기여를 작성하시오.', limit: 800 },
    ]);
  });

  it('번호가 없으면 묻는 말로 끝나는 줄만 문항으로 본다', () => {
    expect(
      shape(`지원 양식 안내
우리 회사에 지원한 동기는 무엇인가요?
입사 후 이루고 싶은 목표를 작성해 주세요. (700자 내외)`),
    ).toEqual([
      { question: '우리 회사에 지원한 동기는 무엇인가요?', limit: null },
      { question: '입사 후 이루고 싶은 목표를 작성해 주세요.', limit: 700 },
    ]);
  });

  it('괄호 없이 끝에 붙은 글자 수도 문항 글에서 뗀다', () => {
    expect(shape('1. 지원 동기를 작성하시오 - 공백 포함 500자 이내')).toEqual([
      { question: '지원 동기를 작성하시오', limit: 500 },
    ]);
  });

  it('채용 사이트 입력칸에서 같이 복사된 「필수0/800」을 떼고 글자 수로 읽는다 — 번호 뒤 띄어쓰기가 없어도', () => {
    expect(
      shape(`1.해당 직무에 지원한 동기와 해당 직무에서 발휘할 수 있는 본인의 강점을 작성해주세요. 필수0/800
2.반복적인 업무나 비효율적인 프로세스를 AI 기술을 접목하여 개선해 본 경험이 있다면, 당시 활용한 도구와 구체적인 성과를 설명해 주세요. 필수0/800
3.혼자만의 성과가 아니라, 다른 사람과의 협업을 통해 더 큰 결과를 만들어냈던 경험을 기술해 주십시오. 필수0/500`),
    ).toEqual([
      { question: '해당 직무에 지원한 동기와 해당 직무에서 발휘할 수 있는 본인의 강점을 작성해주세요.', limit: 800 },
      {
        question:
          '반복적인 업무나 비효율적인 프로세스를 AI 기술을 접목하여 개선해 본 경험이 있다면, 당시 활용한 도구와 구체적인 성과를 설명해 주세요.',
        limit: 800,
      },
      { question: '혼자만의 성과가 아니라, 다른 사람과의 협업을 통해 더 큰 결과를 만들어냈던 경험을 기술해 주십시오.', limit: 500 },
    ]);
  });

  it('번호가 없어도 입력칸 글자 수가 붙은 줄은 문항이다 — 명사로 끝나도', () => {
    expect(
      shape(`지원 동기 필수 0/800
성장 과정 (0/1,000)
입사 후 포부를 작성해 주세요. 0 / 500자`),
    ).toEqual([
      { question: '지원 동기', limit: 800 },
      { question: '성장 과정', limit: 1000 },
      { question: '입사 후 포부를 작성해 주세요.', limit: 500 },
    ]);
  });

  it('줄 끝의 「필수」 표시를 떼고, 빈 줄 뒤 다음 줄의 「0/800」을 글자 수로 붙인다', () => {
    expect(
      shape(`해당 직무에 지원한 동기와 해당 직무에서 발휘할 수 있는 본인의 강점을 작성해주세요. 필수

0/800
반복적인 업무나 비효율적인 프로세스를 AI 기술을 접목하여 개선해 본 경험이 있다면, 당시 활용한 도구와 구체적인 성과를 설명해 주세요. 필수

0/800
혼자만의 성과가 아니라, 다른 사람과의 협업을 통해 더 큰 결과를 만들어냈던 경험을 기술해 주십시오. 필수

0/500
`),
    ).toEqual([
      { question: '해당 직무에 지원한 동기와 해당 직무에서 발휘할 수 있는 본인의 강점을 작성해주세요.', limit: 800 },
      {
        question:
          '반복적인 업무나 비효율적인 프로세스를 AI 기술을 접목하여 개선해 본 경험이 있다면, 당시 활용한 도구와 구체적인 성과를 설명해 주세요.',
        limit: 800,
      },
      { question: '혼자만의 성과가 아니라, 다른 사람과의 협업을 통해 더 큰 결과를 만들어냈던 경험을 기술해 주십시오.', limit: 500 },
    ]);
  });

  it('「(선택)」 · 「*」 필수 표시도 뗀다', () => {
    expect(shape('지원 동기를 작성해 주세요. *\n0/600\n취미를 작성해 주세요. (선택)\n0/300')).toEqual([
      { question: '지원 동기를 작성해 주세요.', limit: 600 },
      { question: '취미를 작성해 주세요.', limit: 300 },
    ]);
  });

  it('입력칸 글자 수만 있는 줄은 앞 문항의 글자 수다', () => {
    expect(shape('1. 지원 동기를 작성해 주세요.\n필수 0/700\n2. 협업 경험을 작성해 주세요.')).toEqual([
      { question: '지원 동기를 작성해 주세요.', limit: 700 },
      { question: '협업 경험을 작성해 주세요.', limit: null },
    ]);
  });

  it('「1.5년」처럼 숫자가 이어지는 줄은 번호 문항이 아니다', () => {
    expect(shape('1.5년 이상 경력자를 우대합니다\n지원 동기를 작성해 주세요.')).toEqual([
      { question: '지원 동기를 작성해 주세요.', limit: null },
    ]);
  });

  it('문항이 없는 글이면 빈 목록', () => {
    expect(shape('이력서 및 자기소개서 제출\n자유양식')).toEqual([]);
  });
});

describe('기본 6문항', () => {
  it('자기소개서 여섯 칸을 문항으로 옮기고, 써 둔 글을 답으로 둔다', () => {
    const qs = defaultQuestions({ motivation: { body: '데이터로 일하고 싶습니다.' } }, ids());
    expect(qs.map((q) => q.question)).toEqual([
      '자기소개', '지원동기', '어려움을 극복한 경험', '성장과정', '성격의 장단점', '입사 후 포부',
    ]);
    expect(qs[1]).toEqual({ id: 'q2', question: '지원동기', limit: null, answer: '데이터로 일하고 싶습니다.' });
    expect(qs[0].answer).toBe('');
  });
});
