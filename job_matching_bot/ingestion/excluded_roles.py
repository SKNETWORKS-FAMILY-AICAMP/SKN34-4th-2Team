"""추천 대상에서 뺄 직종.

채용공고 챗봇은 직군을 가리지 않는다. 다만 배달·배송·운전은 이력서로 매칭할
근거가 거의 없다. 요구하는 것이 기술이 아니라 면허와 근무시간이라, 추천 목록에
섞이면 다른 공고를 밀어낸다. 그래서 이 한 갈래만 제외한다.

단순생산직·포장·지게차는 제외하지 않는다. 생산관리나 품질 직무와 같은 공고에
함께 태그로 붙는 경우가 많아, 빼면 그쪽까지 놓친다.

`기사`가 붙은 태그는 조심해야 한다. 운전기사(택배기사·버스기사)와
기술 자격(전기기사·산업안전기사·대기환경기사)이 같은 글자를 쓴다. 정규식으로
`기사`를 지우면 자격증 요건이 있는 공고까지 날아간다. 그래서 **명시 목록**으로만 뺀다.

제외 판정은 공고의 직종 태그가 **전부** 이 목록에 있을 때만 한다. 통합 채용 공고는
배송과 개발이 함께 태그로 붙는데, 그런 공고까지 빼면 개발 공고를 놓친다.
"""

from __future__ import annotations

from typing import Iterable

# 배달·배송·운송
DELIVERY_ROLES = frozenset({
    "택배기사", "배송기사", "납품운전원", "납품운전원관리", "물류기사", "화물기사",
    "중대형화물차운전원", "라이더(배달원)", "배달", "퀵서비스", "대리운전", "탁송기사",
    "배송", "배송보조", "배송지원", "배송관리", "배송상담", "배송영업부",
    "택배출고", "택배수집", "택배포장", "타일배송준비", "복지용구배송설치",
    "버스기사", "택시기사", "택시운전", "택시운전사", "수행기사", "임원수행기사",
    "의전기사", "셔틀버스기사", "승합기사", "사택기사", "학원차량기사", "마을버스기사",
    "고속버스운전", "대형버스운전", "버스운전", "25인승기사", "45인승기사",
    "구급차기사", "운전", "운전원", "운전직", "운전기사", "운전기사님", "자동차운전",
})

EXCLUDED_ROLES = DELIVERY_ROLES


def _normalize(tag: str) -> str:
    return "".join((tag or "").split()).lower()


_EXCLUDED_KEYS = frozenset(_normalize(role) for role in EXCLUDED_ROLES)


def is_excluded(job_sectors: Iterable[str]) -> bool:
    """직종 태그가 전부 제외 대상이면 True. 태그가 없으면 판단하지 않는다(False)."""
    keys = [_normalize(tag) for tag in job_sectors if (tag or "").strip()]
    if not keys:
        return False
    return all(key in _EXCLUDED_KEYS for key in keys)
