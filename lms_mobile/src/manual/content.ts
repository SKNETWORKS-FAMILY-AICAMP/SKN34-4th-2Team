/**
 * 모바일 앱 사용 설명서 내용 — 역할마다 장(chapter) · 꼭지(block)로 나눈다.
 * 설정 → 「PDF 매뉴얼 보기」가 이 내용으로 PDF 를 만든다(src/manual/html.ts).
 * 화면 문구가 바뀌면 여기도 같이 고친다. 「」 안은 앱에 보이는 글자 그대로다.
 */
export type ManualRole = 'student' | 'instructor' | 'admin';

export interface ManualBlock {
  title: string;
  /** 어디서 여는지 */
  where?: string;
  body?: string;
  steps?: string[];
  bullets?: string[];
  /** 표 — 첫 줄이 머리글 */
  table?: string[][];
  tip?: string;
  /** PC 웹에서 이어서 하는 일 */
  pc?: string;
}

export interface ManualChapter {
  title: string;
  summary: string;
  blocks: ManualBlock[];
}

export interface Manual {
  role: ManualRole;
  roleLabel: string;
  subtitle: string;
  chapters: ManualChapter[];
}

